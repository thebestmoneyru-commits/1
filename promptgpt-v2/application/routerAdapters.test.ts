import { computeWordTrigramOverlap, shouldAcceptAntiCopyRewrite } from "./routerAdapters";

function assert(condition: unknown, message: string): asserts condition {
  if (!condition) throw new Error(`Router adapter self-test failed: ${message}`);
}

export function runRouterAdapterSelfTests(): { passed: number; names: string[] } {
  const names: string[] = [];
  assert(
    shouldAcceptAntiCopyRewrite({
      sourceOverlap: 0.9,
      rewrittenOverlap: 0.62,
      sourceLength: 2400,
      rewrittenLength: 2300,
    }),
    "accept a sufficiently long rewrite with a substantial reduction below the absolute overlap ceiling",
  );
  names.push("accept substantial anti-copy improvement");

  assert(
    !shouldAcceptAntiCopyRewrite({
      sourceOverlap: 0.9,
      rewrittenOverlap: 0.88,
      sourceLength: 2400,
      rewrittenLength: 2300,
    }),
    "reject a cosmetic overlap reduction",
  );
  names.push("reject cosmetic anti-copy improvement");

  assert(
    !shouldAcceptAntiCopyRewrite({
      sourceOverlap: 0.9,
      rewrittenOverlap: 0.6,
      sourceLength: 2400,
      rewrittenLength: 1600,
    }),
    "reject a short rewrite that may have summarized away source content",
  );
  names.push("preserve source-scale output length");

  assert(
    !shouldAcceptAntiCopyRewrite({
      sourceOverlap: 0.9,
      rewrittenOverlap: 0.72,
      sourceLength: 2400,
      rewrittenLength: 2300,
    }),
    "reject a rewrite that remains above the maximum allowed trigram overlap",
  );
  names.push("enforce absolute anti-copy ceiling");


  const userSourceExample = `В рамках атеистической парадигмы смысл человеческого существования неизбежно редуцируется к процессу последовательного и сугубо материального улучшения внешних условий бытия, где всё многообразие мировых явлений выступает не более чем естественным процессом, детерминированным строгими физико-химическими законами. В этой жестко заданной системе координат сам человек предстает лишь результатом случайной комбинации материи, вследствие чего единственно возможный вектор развития мировой истории усматривается в прогрессивном преобразовании вещественного мира. В отсутствие же высших духовных ориентиров именно категория наслаждения закономерно возводится в ранг ключевого мерила "лучшей жизни".

При таком подходе культура призвана лишь инструментально обогащать человеческий опыт, делая его более разнообразным и приятным, в то время как развитие науки и техники обеспечивает индивиду власть над силами природы для удовлетворения постоянно расширяющегося спектра потребностей. Идеалом подобного прогресса провозглашается достижение некоего универсального равенства в доступе к источникам удовольствия, однако именно здесь обнаруживается фундаментальное противоречие: современная урбанистическая среда, выступая средоточием всех цивилизационных достижений, зачастую порождает у субъекта глубокое внутреннее отторжение, диктуемое жаждой первозданной простоты. Более того, ввиду того, что удовольствие одного индивида может фатально оборачиваться страданием для другого, сама идея "общего счастья" оказывается лишенной объективного, универсально применимого измерителя.

Последовательное сведение человеческой сущности к совокупности биохимических реакций фактически элиминирует само понятие свободы выбора, что неминуемо влечет за собой упразднение моральной ответственности и превращение исторического процесса в механическую последовательность фактов, лишенную всякого телеологического обоснования. В такой детерминированной системе, где не остается места ни совести, ни этическому идеалу, атеистическая концепция смысла жизни неизбежно заходит в экзистенциальный тупик. Обещая материальное преуспеяние, она, тем не менее, оказывается неспособной дать ответ на вопрос о финальной цели бытия перед лицом неизбежной смерти, вследствие чего любая модель смысла, базирующаяся исключительно на материи, обнаруживает свою предельную несостоятельность, неизбежно сталкиваясь с неутолимой жаждой вечности, имманентно присущей самой человеческой природе.`;
  const userNearCopyExample = `В атеистической парадигме смысл человеческого существования неизбежно редуцируется к процессу последовательного и сугубо материального улучшения внешних условий бытия. В этой жестко заданной системе координат мировые явления выступают не более чем естественным процессом, детерминированным строгими физико-химическими законами; сам человек предстает лишь результатом случайной комбинации материи, — единственно возможный вектор развития мировой истории усматривается в прогрессивном преобразовании вещественного мира. В отсутствие же высших духовных ориентиров именно категория наслаждения закономерно возводится в ранг ключевого мерила «лучшей жизни». При таком подходе культура призвана лишь инструментально обогащать человеческий опыт, делая его более разнообразным и приятным, кроме того, развитие науки и техники обеспечивает индивиду власть над силами природы для удовлетворения постоянно расширяющегося спектра потребностей. Идеалом подобного прогресса провозглашается достижение некоего универсального равенства в доступе к источникам удовольствия, однако именно здесь обнаруживается фундаментальное противоречие: современная урбанистическая среда, выступая средоточием всех цивилизационных достижений, зачастую порождает у субъекта глубокое внутреннее отторжение, диктуемое жаждой первозданной простоты. Собственно, ввиду того, что удовольствие одного индивида может фатально оборачиваться страданием для другого, сама идея «общего счастья» оказывается лишенной объективного, универсально применимого измерителя. Последовательное сведение человеческой сущности к совокупности биохимических реакций фактически элиминирует само понятие свободы выбора — что неминуемо влечет за собой упразднение моральной ответственности — и превращает исторический процесс в механическую последовательность фактов, лишенную всякого телеологического обоснования. В такой детерминированной системе, где не остается места ни совести, ни этическому идеалу, атеистическая концепция смысла жизни неизбежно заходит в экзистенциальный тупик; обещая материальное преуспеяние, она, тем не менее, оказывается неспособной дать ответ на вопрос о финальной цели бытия перед лицом неизбежной смерти, вследствие чего любая модель смысла, базирующаяся исключительно на материи, обнаруживает свою предельную несостоятельность, неизбежно сталкиваясь с неутолимой жаждой вечности, имманентно присущей самой человеческой природе.`;
  const measuredNearCopyOverlap = computeWordTrigramOverlap(userSourceExample, userNearCopyExample);
  assert(
    measuredNearCopyOverlap > 0.68 &&
      !shouldAcceptAntiCopyRewrite({
        sourceOverlap: 0.9,
        rewrittenOverlap: measuredNearCopyOverlap,
        sourceLength: userSourceExample.length,
        rewrittenLength: userNearCopyExample.length,
      }),
    "the user's exact near-identical source/result example must be rejected as a valid anti-copy rewrite",
  );
  names.push("user-provided near-identical source/result regression fixture");

  return { passed: names.length, names };
}
